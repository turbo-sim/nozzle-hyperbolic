"""Grid sequencing for the two-fluid driver: converge on a coarse mesh, then use
each converged solution as the initial condition of the next, finer mesh.

    python run_grid_sequence.py [settings/settings_xxx.yaml]   (path relative to dev_scripts/)

Reads a `grid_sequence:` block from the settings file (main_two_fluid.py
ignores it):

    grid_sequence:
      Nx:      [100, 300, 600]          # coarse → fine
      ssr_tol: [1.0e-6, 1.0e-6, 1.0e-8] # optional, one per level
                                        # (default: run.ssr_tol on every level)

Level 1 runs the settings file as is — typically ic.type: stagnation with a
ramped start-up (bc.p_out_ramp_steps > 0).  Every later level restarts from the
previous level's solution (ic.type: restart, interpolated onto the new grid)
with the ramp switched off.  Each level is an ordinary main_two_fluid.py run
and writes an ordinary results folder; the generated per-level settings files
(complete, `base: none` — the defaults chain is resolved here) and a summary.txt
go into <repo_main>/<repo_run>_sequence_<timestamp>/.
The sequence stops at the first level that does not converge.
"""
import copy
import datetime as dt
import os
import pathlib
import re
import subprocess
import sys

import yaml

from config_loader import resolved_dict

HERE = pathlib.Path(__file__).parent
DRIVER = HERE / "main_two_fluid.py"


def _run_level(settings_path):
    """Run main_two_fluid.py on one settings file, streaming its output.
    Returns (output_dir, stop_line, summary_line)."""
    env = dict(os.environ, SETTINGS_YAML=str(settings_path),
               MPLBACKEND="Agg", PYTHONIOENCODING="utf-8")
    proc = subprocess.Popen([sys.executable, "-u", str(DRIVER)], cwd=HERE, env=env,
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                            text=True, encoding="utf-8", errors="replace")
    out_dir = stop = summary = None
    for line in proc.stdout:
        print(line, end="", flush=True)
        if line.startswith("Output directory:"):
            out_dir = pathlib.Path(line.split(":", 1)[1].strip())
        elif line.startswith("Stopped:"):
            stop = line.strip()
        elif line.strip().startswith("steps="):
            summary = line.strip()
    proc.wait()
    if proc.returncode != 0:
        raise RuntimeError(f"main_two_fluid.py exited with code {proc.returncode}")
    return out_dir, stop, summary


def main():
    base_name = (sys.argv[1] if len(sys.argv) > 1
                 else "settings/settings_flashing_smd_supersonic_test.yaml")
    base_path = (HERE / base_name).resolve()
    base = resolved_dict(base_path)        # defaults chain merged in

    seq = base.get("grid_sequence")
    if not seq or not seq.get("Nx"):
        sys.exit(f"{base_path.name}: no grid_sequence.Nx list — nothing to do")
    levels = [int(n) for n in seq["Nx"]]
    tols = seq.get("ssr_tol", [base["run"]["ssr_tol"]] * len(levels))
    if len(tols) != len(levels):
        sys.exit("grid_sequence.ssr_tol must have one entry per grid_sequence.Nx level")

    so = base.get("save_options") or {}
    repo_main = (HERE / str(so.get("repo_main") or "results")).resolve()
    prefix = str(so.get("repo_run") or "grid_sequence")
    seq_dir = repo_main / f"{prefix}_sequence_{dt.datetime.now():%Y%m%d_%H%M%S}"
    seq_dir.mkdir(parents=True, exist_ok=True)
    print(f"Grid sequence {levels}  →  {seq_dir}")

    rows, prev_dir = [], None
    for i, (nx, tol) in enumerate(zip(levels, tols), start=1):
        cfg = copy.deepcopy(base)
        cfg.pop("grid_sequence", None)
        cfg["grid"]["Nx"] = nx
        cfg["run"]["ssr_tol"] = float(tol)
        cfg.setdefault("save_options", {})
        cfg["save_options"]["repo_main"] = str(repo_main)
        cfg["save_options"]["repo_run"] = f"{prefix}_L{i}"
        if prev_dir is not None:
            # Finer level: start from the previous converged solution (linear
            # interpolation in x happens in the driver's 'restart' IC); no ramp.
            cfg["ic"] = {"type": "restart", "run": str(prev_dir)}
            cfg["bc"]["p_out_ramp_steps"] = 0
        level_yaml = seq_dir / f"level{i}_N{nx}.yaml"
        with open(level_yaml, "w", encoding="utf-8") as f:
            f.write(f"# Level {i} of the grid sequence of {base_path}\n"
                    f"# (generated by run_grid_sequence.py; defaults chain resolved)\n")
            yaml.safe_dump(cfg, f, sort_keys=False, allow_unicode=True)

        print(f"\n{'=' * 78}\nLevel {i}/{len(levels)}: Nx={nx}  ssr_tol={float(tol):.1e}  "
              f"IC={cfg['ic']['type']}\n{'=' * 78}", flush=True)
        out_dir, stop, summary = _run_level(level_yaml)
        rows.append((i, nx, stop or "?", summary or "?", out_dir))
        if out_dir is None or stop is None or not re.search(r"SSR=.*< tol", stop):
            print(f"\nLevel {i} did not converge ({stop}) — stopping the sequence.")
            break
        prev_dir = out_dir

    lines = [f"Grid sequence from {base_path.name}: Nx={levels}", ""]
    lines += [f"L{i}  N={nx:<5d} {summary:<55s} {stop}\n     {out}" for i, nx, stop, summary, out in rows]
    (seq_dir / "summary.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n" + "\n".join(lines))


if __name__ == "__main__":
    main()
