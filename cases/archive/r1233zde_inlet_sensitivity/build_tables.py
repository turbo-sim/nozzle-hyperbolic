FIG_DIR = cfg.TABLE_DIR / "figures"
REPORT  = cfg.TABLE_DIR / "table_verification.txt"

# Properties the two-fluid solver actually reads out of the tables every step.
SOLVER_PROPS = ["density", "temperature", "speed_of_sound", "entropy",
                "gruneisen", "isobaric_heat_capacity", "viscosity",
                "conductivity"]

# Accuracy gates for the round-trip check in the STABLE region.
TOL_TIGHT = 1.0e-3     # rho, T  - bicubic on a 90x90 log-p grid
TOL_LOOSE = 1.0e-2     # a, s, cp - built from table gradients, noisier


class Report:
    """Tee everything to stdout and to the verification report file."""

    def __init__(self, path):
        self.lines = []
        self.path = path
        self.failures = []
        self.warnings = []

    def __call__(self, msg=""):
        print(msg, flush=True)
        self.lines.append(str(msg))

    def check(self, ok, label, detail="", warn_only=False):
        if ok:
            tag = "PASS"
        elif warn_only:
            tag = "WARN"
            self.warnings.append(label)
        else:
            tag = "FAIL"
            self.failures.append(label)
        self(f"  [{tag}] {label}" + (f"   {detail}" if detail else ""))
        return ok

    def save(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.path.write_text("\n".join(self.lines) + "\n", encoding="utf-8")
        print(f"\nVerification report written to: {self.path}")


def frozen_mask(table, phase):
    """Boolean (N_h, N_p) mask of nodes the generator FROZE past the spinodal.

    The generator copies the previous node verbatim when the metastable solve
    fails or the isothermal bulk modulus turns negative, marching h upward for
    the liquid and downward for the vapour.  An exact float equality with the
    upstream neighbour is therefore a reliable frozen-node fingerprint.
    """
    rho = np.asarray(table["density"]["value"])
    m = np.zeros_like(rho, dtype=bool)
    if phase == "liquid":                      # marched i = 0 -> N_h-1
        m[1:, :] = rho[1:, :] == rho[:-1, :]
        for i in range(1, m.shape[0]):         # freeze latches for the column
            m[i, :] |= m[i - 1, :]
    else:                                      # vapour marched i = N_h-1 -> 0
        m[:-1, :] = rho[:-1, :] == rho[1:, :]
        for i in range(m.shape[0] - 2, -1, -1):
            m[i, :] |= m[i + 1, :]
    return m


def verify(fluid, lut, phase, rep: Report):
    name = "LIQUID (dominant)" if phase == "liquid" else "VAPOUR (ghost)"
    rep()
    rep("=" * 78)
    rep(f"TABLE: {name}   {fluid.table_name}")
    rep("=" * 78)

    table = fluid.table
    h_vals = np.asarray(fluid.h_vals)
    p_vals = np.exp(np.asarray(fluid.logP_vals))
    Q = 0.0 if phase == "liquid" else 1.0

    # -- 1. metadata matches the requested specification --------------------
    rep("\n1. Metadata / requested bounds")
    meta = table["metadata"]
    for k in ("h_min", "h_max", "p_min", "p_max", "N_h", "N_p"):
        rep.check(meta[k] == lut[k], f"metadata {k} = {meta[k]!r}",
                  f"(requested {lut[k]!r})")
    rep.check(meta["fluid"] == cfg.FLUID_NAME, f"fluid = {meta['fluid']}")
    rep.check(meta["metastable_phase"] == phase,
              f"metastable_phase = {meta['metastable_phase']}")
    rep(f"       h grid: {h_vals[0]/1e3:.2f} .. {h_vals[-1]/1e3:.2f} kJ/kg  "
        f"({len(h_vals)} nodes, dh = {(h_vals[1]-h_vals[0])/1e3:.3f} kJ/kg)")
    rep(f"       p grid: {p_vals[0]/1e5:.4f} .. {p_vals[-1]/1e5:.4f} bar  "
        f"({len(p_vals)} nodes, log-spaced)")

    # -- 2. finiteness of values, gradients and bicubic coefficients --------
    rep("\n2. Finiteness (values, gradients, bicubic coefficients)")
    bad = []
    for k in SOLVER_PROPS:
        for sub in ("value", "grad_h", "grad_p", "coeffs"):
            arr = np.asarray(table[k][sub])
            if not np.isfinite(arr).all():
                bad.append(f"{k}.{sub} ({int((~np.isfinite(arr)).sum())} nodes)")
    rep.check(not bad, "no NaN/Inf anywhere in the solver-used properties",
              "; ".join(bad))
    kk = np.asarray(table["conductivity"]["value"])
    rep(f"       NOTE: conductivity is an R245fa corresponding-states ESTIMATE "
        f"({kk.min():.4f} .. {kk.max():.4f} W/m/K);")
    rep( "             CoolProp has no conductivity model for R1233zd(E).  It "
         "enters ONLY the interfacial")
    rep( "             HTC, never the EOS.  See patch_conductivity.py.")

    # -- 3. spinodal-freeze audit ------------------------------------------
    rep("\n3. Spinodal-freeze audit (metastable extension)")
    fm = frozen_mask(table, phase)
    frac = fm.mean()
    rep(f"       frozen nodes: {int(fm.sum())} / {fm.size}  ({frac*100:.1f} %)")
    per_col = fm.mean(axis=0)
    rep(f"       per-pressure-column frozen fraction: "
        f"min {per_col.min()*100:.1f} %  max {per_col.max()*100:.1f} %")
    # The catastrophic failure mode is a table that is frozen essentially
    # everywhere (the historical broadcast-row bug).
    rep.check(frac < 0.90, "table is not globally frozen (the 2026-07 bug)",
              f"frozen fraction {frac*100:.1f} %")
    # The stable side must never be frozen: for every pressure column the
    # saturation enthalpy must sit in the live region.
    n_sat_frozen = 0
    for j, p in enumerate(p_vals):
        if p >= cfg.P_CRIT * 0.999:
            continue
        h_sat = CP.PropsSI("H", "P", float(p), "Q", Q, cfg.FLUID_NAME)
        if not (h_vals[0] <= h_sat <= h_vals[-1]):
            continue
        i = int(np.searchsorted(h_vals, h_sat))
        i = min(max(i, 0), fm.shape[0] - 1)
        if fm[i, j]:
            n_sat_frozen += 1
    rep.check(n_sat_frozen == 0,
              "saturation line lies in the LIVE (non-frozen) region for every "
              "pressure column", f"{n_sat_frozen} columns frozen at h_sat")

    # -- 4. accuracy against CoolProp in the STABLE single-phase region -----
    rep("\n4. Round-trip accuracy vs CoolProp (stable single-phase region)")
    hs, ps = [], []
    rng = np.random.default_rng(0)
    for _ in range(4000):
        p = float(np.exp(rng.uniform(np.log(p_vals[0] * 1.02),
                                     np.log(p_vals[-1] * 0.98))))
        if p >= cfg.P_CRIT * 0.995:
            continue
        try:
            h_sat = CP.PropsSI("H", "P", p, "Q", Q, cfg.FLUID_NAME)
        except Exception:
            continue
        # stable side: subcooled liquid (h < h_sat) / superheated vapour (h > h_sat)
        lo, hi = ((h_vals[0], min(h_sat * 0.999, h_vals[-1])) if phase == "liquid"
                  else (max(h_sat * 1.001, h_vals[0]), h_vals[-1]))
        if not (hi > lo):
            continue
        hs.append(float(rng.uniform(lo, hi)))
        ps.append(p)
    hs, ps = np.array(hs), np.array(ps)
    rep(f"       {len(hs)} random stable-region probe points")

    st = fluid.get_state(jxp.HmassP_INPUTS, jnp.array(hs), jnp.array(ps))
    ref = {"density": "D", "temperature": "T", "speed_of_sound": "A",
           "entropy": "S", "isobaric_heat_capacity": "C"}
    for prop, cp_key in ref.items():
        got = np.asarray(st[prop])
        want = np.array([CP.PropsSI(cp_key, "H", h, "P", p, cfg.FLUID_NAME)
                         for h, p in zip(hs, ps)])
        err = np.abs(got - want) / np.maximum(np.abs(want), 1e-30)
        tol = TOL_TIGHT if prop in ("density", "temperature") else TOL_LOOSE
        rep.check(np.nanmedian(err) < tol, f"{prop:24s} median rel. err",
                  f"med {np.nanmedian(err):.2e}  p95 {np.nanpercentile(err,95):.2e}  "
                  f"max {np.nanmax(err):.2e}  (tol {tol:.0e})")

    # -- 5. saturation-property line ---------------------------------------
    rep("\n5. Saturation-property line (used by the mass-transfer closure)")
    p_probe = np.exp(np.linspace(np.log(p_vals[0] * 1.02),
                                 np.log(cfg.P_CRIT * 0.95), 200))
    sat = fluid.get_state_saturation(jnp.array(p_probe))
    for prop, cp_key in (("temperature", "T"), ("enthalpy", "H"),
                         ("density", "D")):
        got = np.asarray(sat[prop])
        want = np.array([CP.PropsSI(cp_key, "P", p, "Q", Q, cfg.FLUID_NAME)
                         for p in p_probe])
        err = np.abs(got - want) / np.maximum(np.abs(want), 1e-30)
        rep.check(np.nanmedian(err) < TOL_LOOSE,
                  f"sat {prop:20s} median rel. err",
                  f"med {np.nanmedian(err):.2e}  max {np.nanmax(err):.2e}")

    # -- 6. physical sanity in the live region ------------------------------
    rep("\n6. Physical sanity in the live region")
    live = ~fm
    rho = np.asarray(table["density"]["value"])
    T   = np.asarray(table["temperature"]["value"])
    a   = np.asarray(table["speed_of_sound"]["value"])
    rep.check(bool((rho[live] > 0).all()), "density > 0",
              f"min {rho[live].min():.4e} kg/m3")
    rep.check(bool((T[live] > 0).all()), "temperature > 0",
              f"min {T[live].min():.2f} K")
    rep.check(bool((a[live] > 0).all()), "speed of sound > 0 (a^2 > 0)",
              f"min {a[live].min():.3f} m/s")
    # rho must fall as h rises at fixed p (both phases, whole live region)
    drho = np.diff(rho, axis=0)
    ok_mono = np.all(drho[live[1:, :] & live[:-1, :]] <= 0)
    rep.check(bool(ok_mono), "density monotonically decreasing in h at fixed p",
              warn_only=True)

    return fm, h_vals, p_vals


def plot_maps(fluid, lut, phase, fm, h_vals, p_vals):
    """Diagnostic maps: rho, T, a and the frozen mask, with the saturation line
    and the case operating box overlaid."""
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    table = fluid.table
    Q = 0.0 if phase == "liquid" else 1.0

    p_sat = np.exp(np.linspace(np.log(p_vals[0]), np.log(cfg.P_CRIT * 0.999), 300))
    h_sat = np.array([CP.PropsSI("H", "P", p, "Q", Q, cfg.FLUID_NAME)
                      for p in p_sat])

    H, P = np.meshgrid(h_vals / 1e3, p_vals / 1e5, indexing="ij")
    fields = [("density", "rho [kg/m3]"), ("temperature", "T [K]"),
              ("speed_of_sound", "a [m/s]")]

    fig, axes = plt.subplots(1, 4, figsize=(20, 5), constrained_layout=True)
    for ax, (key, label) in zip(axes, fields):
        v = np.asarray(table[key]["value"]).copy()
        v[fm] = np.nan                       # show only physical states
        m = ax.pcolormesh(H, P, v, shading="auto", cmap="viridis")
        fig.colorbar(m, ax=ax, label=label)
        ax.set_title(f"{label}  (frozen nodes blanked)")
    axes[3].pcolormesh(H, P, fm.astype(float), shading="auto", cmap="Reds",
                       vmin=0, vmax=1)
    axes[3].set_title("frozen past spinodal (red = frozen)")

    for ax in axes:
        ax.plot(h_sat / 1e3, p_sat / 1e5, "w-", lw=2.0)
        ax.plot(h_sat / 1e3, p_sat / 1e5, "k--", lw=1.2, label="saturation line")
        # case operating box: p_out .. p0
        ax.axhline(cfg.P0 / 1e5, color="cyan", lw=1.2, ls=":")
        ax.axhline(cfg.P_OUT / 1e5, color="cyan", lw=1.2, ls=":")
        h0 = cfg.H_L0 if phase == "liquid" else cfg.H_G0
        ax.plot([h0 / 1e3], [cfg.P0 / 1e5], "r*", ms=14,
                label="reservoir state")
        ax.set_yscale("log")
        ax.set_xlabel("h [kJ/kg]")
        ax.set_ylabel("p [bar]")
        ax.legend(loc="lower right", fontsize=7)

    fig.suptitle(f"R1233zd(E) metastable {phase} table  {lut['N_h']}x{lut['N_p']}"
                 f"   h [{lut['h_min']/1e3:.0f}, {lut['h_max']/1e3:.0f}] kJ/kg"
                 f"   p [{lut['p_min']/1e5:.2f}, {lut['p_max']/1e5:.2f}] bar")
    out = FIG_DIR / f"table_map_{phase}.png"
    fig.savefig(out, dpi=130)
    plt.close(fig)
    print(f"  map saved: {out}")


def operating_envelope(fluid_g, fluid_l, fm_g, fm_l, rep: Report):
    """Check the states the SOLVER will actually visit are inside the tables
    and in the live (non-frozen) region."""
    rep()
    rep("=" * 78)
    rep("OPERATING ENVELOPE - will the solver stay inside valid table data?")
    rep("=" * 78)

    rep("\n7. Reservoir state")
    for nm, h0, lo, hi in (("liquid h_l0", cfg.H_L0, cfg.H_LIQ_MIN, cfg.H_LIQ_MAX),
                           ("vapour h_g0", cfg.H_G0, cfg.H_VAP_MIN, cfg.H_VAP_MAX)):
        rep.check(lo < h0 < hi, f"{nm} = {h0/1e3:.2f} kJ/kg inside table",
                  f"margins: {(h0-lo)/1e3:+.2f} kJ/kg above h_min, "
                  f"{(hi-h0)/1e3:+.2f} kJ/kg below h_max")
    rep.check(cfg.P_TABLE_MIN < cfg.P0 < cfg.P_TABLE_MAX,
              f"p0 = {cfg.P0/1e5:.4f} bar inside table",
              f"margins: x{cfg.P0/cfg.P_TABLE_MIN:.2f} above p_min, "
              f"x{cfg.P_TABLE_MAX/cfg.P0:.2f} below p_max")
    rep.check(cfg.P_TABLE_MIN < cfg.P_OUT,
              f"p_out = {cfg.P_OUT/1e5:.4f} bar above the table floor",
              f"margin x{cfg.P_OUT/cfg.P_TABLE_MIN:.2f}")

    rep("\n8. Expansion path p0 -> p_out (equilibrium saturation states)")
    rep("       the flashing solution tracks the saturation line closely; both")
    rep("       phases must stay in-table and live along the whole path")
    p_path = np.exp(np.linspace(np.log(cfg.P_OUT), np.log(cfg.P0), 40))
    out_l = out_g = frz_l = frz_g = 0
    for p in p_path:
        hl = CP.PropsSI("H", "P", float(p), "Q", 0, cfg.FLUID_NAME)
        hg = CP.PropsSI("H", "P", float(p), "Q", 1, cfg.FLUID_NAME)
        if not (cfg.H_LIQ_MIN <= hl <= cfg.H_LIQ_MAX):
            out_l += 1
        if not (cfg.H_VAP_MIN <= hg <= cfg.H_VAP_MAX):
            out_g += 1
        for fl, fm, h, cnt in ((fluid_l, fm_l, hl, "l"), (fluid_g, fm_g, hg, "g")):
            hv = np.asarray(fl.h_vals)
            pv = np.exp(np.asarray(fl.logP_vals))
            if not (hv[0] <= h <= hv[-1]):
                continue
            i = min(int(np.searchsorted(hv, h)), fm.shape[0] - 1)
            j = min(int(np.searchsorted(pv, p)), fm.shape[1] - 1)
            if fm[i, j]:
                if cnt == "l":
                    frz_l += 1
                else:
                    frz_g += 1
    rep.check(out_l == 0, "saturated-liquid enthalpy in-table over p_out..p0",
              f"{out_l}/{len(p_path)} points outside")
    rep.check(out_g == 0, "saturated-vapour enthalpy in-table over p_out..p0",
              f"{out_g}/{len(p_path)} points outside")
    rep.check(frz_l == 0, "liquid saturation path in the live region",
              f"{frz_l}/{len(p_path)} frozen")
    rep.check(frz_g == 0, "vapour saturation path in the live region",
              f"{frz_g}/{len(p_path)} frozen")

    rep("\n9. Headroom notes (not pass/fail)")
    h_l_sat_top = CP.PropsSI("H", "P", float(cfg.P0), "Q", 0, cfg.FLUID_NAME)
    rep(f"       liquid h_max = {cfg.H_LIQ_MAX/1e3:.0f} kJ/kg is "
        f"{(cfg.H_LIQ_MAX-h_l_sat_top)/1e3:.1f} kJ/kg above h_l,sat(p0); the "
        f"liquid table stops covering the")
    rep( "       saturation line only above ~35 bar, which this case never reaches "
         f"(p0 = {cfg.P0/1e5:.2f} bar).")
    rep(f"       The BINDING constraint downstream is the table floor "
        f"p_min = {cfg.P_TABLE_MIN/1e5:.2f} bar: if the divergent over-expands")
    rep(f"       below it the solver leaves the table.  run_simulation.py monitors "
        f"this every {cfg.PRINT_EVERY} steps.")


def main():
    cfg.TABLE_DIR.mkdir(parents=True, exist_ok=True)
    rep = Report(REPORT)

    rep("R1233zd(E) EOS TABLE BUILD + VERIFICATION")
    rep("=" * 78)
    rep(cfg.summary())
    rep()
    rep(f"CoolProp version : {CP.get_global_param_string('version')}")
    rep(f"canonical name   : {CP.get_fluid_param_string(cfg.FLUID_NAME, 'name')}")
    rep(f"aliases          : {CP.get_fluid_param_string(cfg.FLUID_NAME, 'aliases')}")
    rep("NOTE: enthalpy/entropy are reference-state dependent.  All bounds in")
    rep("      case_config.py are expressed in THIS CoolProp build's reference")
    rep("      state; the verification below re-derives everything from it.")

    rep("\nBuilding / loading tables ...")
    fluid_g, fluid_l = cfg.build_fluids()

    # CoolProp has NO thermal-conductivity model for R1233zd(E), so the
    # generator stores NaN at every node - and the interfacial-HTC closure reads
    # conductivity for both phases.  Fill it by corresponding states from R245fa
    # and reload, before anything is verified.  See patch_conductivity.py.
    _k_nan = not np.isfinite(
        np.asarray(fluid_l.table["conductivity"]["value"])).all()
    if _k_nan:
        rep("\nThermal conductivity is NaN (CoolProp has no model for this "
            "fluid) - patching from R245fa by corresponding states ...")
        import patch_conductivity
        if patch_conductivity.main() != 0:
            rep("  [FAIL] conductivity patch failed")
            rep.failures.append("conductivity patch")
        del fluid_g, fluid_l
        fluid_g, fluid_l = cfg.build_fluids(verbose=False)
        rep("  tables reloaded with conductivity filled in.")

    fm_l, hl, pl = verify(fluid_l, cfg.lut_liquid(), "liquid", rep)
    fm_g, hg, pg = verify(fluid_g, cfg.lut_vapor(),  "vapor",  rep)

    operating_envelope(fluid_g, fluid_l, fm_g, fm_l, rep)

    rep("\nWriting diagnostic maps ...")
    plot_maps(fluid_l, cfg.lut_liquid(), "liquid", fm_l, hl, pl)
    plot_maps(fluid_g, cfg.lut_vapor(),  "vapor",  fm_g, hg, pg)

    rep()
    rep("=" * 78)
    if rep.failures:
        rep(f"RESULT: {len(rep.failures)} CHECK(S) FAILED")
        for f in rep.failures:
            rep(f"   - {f}")
    else:
        rep("RESULT: ALL CHECKS PASSED")
    if rep.warnings:
        rep(f"  {len(rep.warnings)} warning(s):")
        for w in rep.warnings:
            rep(f"   - {w}")
    rep("=" * 78)
    rep.save()
    return 1 if rep.failures else 0


if __name__ == "__main__":
    sys.exit(main())
