"""
Build and VERIFY the two R1233zd(E) bicubic EOS tables for this case.
=====================================================================

Run this once before `run_simulation.py`:

    python build_tables.py

It builds (or reloads) the metastable-liquid and metastable-vapour tables
declared in `case_config.py` into ./fluid_tables/, then runs a verification
suite and writes ./fluid_tables/table_verification.txt plus diagnostic maps in
./fluid_tables/figures/.

Why the verification matters
----------------------------
A metastable table is generated by marching each pressure column into the
superheated-liquid / subcooled-vapour region until the SPINODAL is crossed;
past that point CoolProp has no root and the generator FREEZES the last good
node (constant extrapolation).  That is by design, but it means two things can
silently go wrong:

  1. the freeze can trip far too early - a past jaxprop bug latched the freeze
     globally and shipped a table that was one enthalpy row broadcast over the
     whole (h,p) plane;
  2. the requested h-window can be so deep into the metastable region that the
     part of the table the solver actually visits is frozen garbage.

Checks 5 and 6 below are aimed squarely at both.  The pass/fail criterion that
matters is not "is the whole rectangle exact" (it cannot be - beyond the
spinodal there is no physical state) but "is every state the SOLVER will visit
in a live, non-frozen, CoolProp-accurate region".
"""

